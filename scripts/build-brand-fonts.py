#!/usr/bin/env python3
"""Builds the generated brand font files. Rerun only when a source font changes.

Redaction's "1" reads as a lowercase "l", so digits in the serif come from Newsreader
(Production Type, SIL Open Font License), whose "1" has a flag and a foot.

usage: python3 scripts/build-brand-fonts.py <newsreader-dir>

<newsreader-dir> holds `Newsreader[opsz,wght].ttf` and `Newsreader-Italic[opsz,wght].ttf`, as in
ofl/newsreader of https://github.com/google/fonts. Needs fonttools and brotli.

Writes:
  apps/web/src/fonts/newsreader/newsreader-figures{,-italic}.woff2
      Newsreader's digits 0-9 only, weights 400 to 700, at the 18pt optical size. The web app
      puts them first in the serif stacks, limited to U+0030-0039.
  apps/mobile/assets/fonts/DoeDeskSerif-{Regular,Italic,Bold}.ttf
      Redaction with those digits in place of its own, because native text takes one family
      and cannot fall back per character. Renamed "DoeDesk Serif": it is a modified version
      of both fonts. Both licences sit beside the files.
"""

import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
from fontTools.ttLib.scaleUpem import scale_upem
from fontTools.varLib import instancer

REPO = Path(__file__).resolve().parent.parent
REDACTION = REPO / "apps/web/src/fonts/redaction"
WEB_OUT = REPO / "apps/web/src/fonts/newsreader"
MOBILE_OUT = REPO / "apps/mobile/assets/fonts"
DIGITS = range(0x30, 0x3A)
OPTICAL_SIZE = 18
COPYRIGHT = (
    "Copyright 2019 MCKL Inc. Digits: Copyright 2020 The Newsreader Project Authors "
    "(http://github.com/productiontype/Newsreader). A modified version of Redaction and "
    "Newsreader, under the SIL Open Font License 1.1."
)


def reload(font: TTFont) -> TTFont:
    """Instancing leaves lazy tables the subsetter and pens trip over; a round trip settles them."""
    buffer = io.BytesIO()
    font.save(buffer)
    buffer.seek(0)
    return TTFont(buffer, recalcTimestamp=False)


def build_web_figures(newsreader: Path, donor: str, name: str) -> None:
    font = TTFont(newsreader / donor, recalcTimestamp=False)
    font = reload(
        instancer.instantiateVariableFont(font, {"wght": (400, 700), "opsz": OPTICAL_SIZE})
    )
    options = subset.Options()
    options.layout_features = ["kern"]
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=DIGITS)
    subsetter.subset(font)
    font.flavor = "woff2"
    WEB_OUT.mkdir(parents=True, exist_ok=True)
    out = WEB_OUT / name
    font.save(out)
    print(f"{out.relative_to(REPO)}: {out.stat().st_size} bytes")


def build_mobile_face(newsreader: Path, source: str, donor: str, weight: int, style: str) -> None:
    base = TTFont(REDACTION / source, recalcTimestamp=False)
    base.flavor = None
    donor_font = TTFont(newsreader / donor, recalcTimestamp=False)
    donor_font = reload(
        instancer.instantiateVariableFont(donor_font, {"wght": weight, "opsz": OPTICAL_SIZE})
    )
    scale_upem(donor_font, base["head"].unitsPerEm)
    donor_glyphs = donor_font.getGlyphSet()
    donor_cmap = donor_font.getBestCmap()

    # The digits go in as new glyphs, so Redaction's kerning and substitutions for its own
    # digits, drawn for other shapes and widths, do not apply to them.
    for code in DIGITS:
        name = f"{donor_cmap[code]}.figure"
        recording = DecomposingRecordingPen(donor_glyphs)
        donor_glyphs[donor_cmap[code]].draw(recording)
        pen = TTGlyphPen(None)
        recording.replay(pen)
        base["glyf"][name] = pen.glyph()
        base["hmtx"][name] = donor_font["hmtx"][donor_cmap[code]]
        for table in base["cmap"].tables:
            if code in table.cmap:
                table.cmap[code] = name
    base.setGlyphOrder(base["glyf"].glyphOrder)

    family, postscript = "DoeDesk Serif", f"DoeDeskSerif-{style}"
    names = base["name"]
    names.names = [record for record in names.names if record.nameID not in (16, 17, 18, 21, 22)]
    for name_id, value in {
        0: COPYRIGHT,
        1: family,
        2: style,
        3: f"{postscript};generated by scripts/build-brand-fonts.py",
        4: f"{family} {style}",
        6: postscript,
    }.items():
        names.setName(value, name_id, 3, 1, 0x409)
        names.setName(value, name_id, 1, 0, 0)

    out = MOBILE_OUT / f"{postscript}.ttf"
    base.save(out)
    print(f"{out.relative_to(REPO)}: {out.stat().st_size} bytes")


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    newsreader = Path(sys.argv[1])
    upright, italic = "Newsreader[opsz,wght].ttf", "Newsreader-Italic[opsz,wght].ttf"
    build_web_figures(newsreader, upright, "newsreader-figures.woff2")
    build_web_figures(newsreader, italic, "newsreader-figures-italic.woff2")
    build_mobile_face(newsreader, "redaction-latin-400-normal.woff2", upright, 400, "Regular")
    build_mobile_face(newsreader, "redaction-latin-400-italic.woff2", italic, 400, "Italic")
    build_mobile_face(newsreader, "redaction-latin-700-normal.woff2", upright, 700, "Bold")


if __name__ == "__main__":
    main()
